/*
 * Asymmetric fast-path bounds (signed double comparison).
 * Positive limit: largest x with finite exp(x) (overflow boundary).
 * Negative limit: most negative x with exp(x) >= DBL_MIN (denormal boundary,
 * -1022*ln(2)).  NaN is caught by the negated-range idiom below.
 */
#define EXP_MAX_POS   0x1.62e42fefa39efp+9   /* 709.7827...: overflow boundary */
#define EXP_MIN_NEG  (-0x1.6232bdd7abcd2p+9)  /* -708.3964...: denormal boundary */

#define FMIN_X        -0x1.74910d52d3051p+9   /* -745.13: full underflow to zero */
#define DENORMAL_LOW  -0x1.74046dfefd9d0p+9   /* -744.04: boundary for denormal result */
#define DENORMAL_MIN   0x0000000000000001ULL   /* smallest positive denormal */

#define SCALAR_EXP ALM_PROTO_OPT(exp)

v_f64x2_t
ALM_PROTO_OPT(vrd2_exp)(v_f64x2_t x)
{
    /* Branch-free, domain-check-free reconstruction */
    v_f64x2_t ret = vrd2_exp_fastpath(x);

    for(int i = 0; i < 2; i++)
    {
        if(unlikely(!(x[i] <= EXP_MAX_POS && x[i] >= EXP_MIN_NEG))) {
            if (x[i] <= FMIN_X)
                ret[i] = 0.0;
            else if (x[i] <= DENORMAL_LOW)
                ret[i] = asdouble(DENORMAL_MIN);
            else
                ret[i] = SCALAR_EXP(x[i]);
        }
    }

    return ret;
}
