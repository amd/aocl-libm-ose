/*
 * C implementation of exp double precision 128-bit vector version (v2d)
 *
 * Signature:
 *   v_f64x2_t vrd2_exp(v_f64x2_t x)
 *
 * Algorithm: Table-based range reduction with 64-entry table + degree-5 polynomial
 *
 *   Range reduction and reconstruction follow the scalar exp() fast path
 *   (src/optimized/exp.c), with Sollya-minimax coefficients tuned for vrd2_exp.
 *
 * Implementation Notes
 * ----------------------
 *
 * 1. Argument Reduction:
 *      e^x = 2^(x/ln2) = 2^(x*(64/ln(2))/64)           --- (1)
 *
 *      Choose 'n' and 'f', such that
 *      x * 64/ln2 = n + f                                --- (2)
 *                                     where n is integer, |f| <= 0.5
 *
 *      Choose 'm' and 'j' such that,
 *      n = (64 * m) + j                                  --- (3)
 *                                     where 0 <= j < 64
 *
 *      From (1), (2) and (3),
 *      e^x = 2^((64*m + j + f)/64)
 *          = (2^m) * (2^(j/64)) * 2^(f/64)
 *          = (2^m) * (2^(j/64)) * e^(f*(ln(2)/64))
 *
 * 2. Table Lookup:
 *      Values of (2^(j/64)) are precomputed for j = 0, 1, 2 ... 63,
 *      stored as {head, tail} double-double pairs (~106-bit precision):
 *        head = double(2^(j/64))         — best 53-bit approximation
 *        tail = double(2^(j/64) - head)  — error term (bits 54-106)
 *      Table data: src/optimized/data/_exp_tbl_64_2field.data
 *      Generated by: tools/sollya/gen_exp_tbl_2field.sollya
 *
 * 3. Polynomial Evaluation:
 *      From (2),
 *        f = x*(64/ln(2)) - n
 *      Let,
 *        r = f*(ln(2)/64) = x - n*(ln(2)/64)
 *
 *      Since |f| <= 0.5, we have |r| <= ln(2)/128 ≈ 0.0054.
 *      This narrow range allows a degree-5 Sollya minimax polynomial
 *      to approximate (e^r - 1) with sub-ULP accuracy (60 bits,
 *      8-bit margin for double). Since c0=0 and c1=1, factoring
 *      out r saves one FMA (POLY_EVAL_4 macro with FMA):
 *        q = r * (1 + C2*r + C3*r^2 + C4*r^3 + C5*r^4)
 *
 * 4. Reconstruction:
 *        e^x = (2^m) * (2^(j/64)) * e^r
 *
 *      head + tail is a double-double approximation of 2^(j/64)
 *      with ~106 bits of precision. Since |tail| ≈ 2^-53 * |head|
 *      and |poly| ≈ 0.005, tail*poly ≈ 2^-61 (~0.0003 ULPs) is
 *      negligible, and the reconstruction simplifies to 1 FMA + 1 ADD:
 *        inner = fma(head, poly, tail)   // head*poly + tail
 *        q     = head + inner            // head*(1+poly) + tail
 *      Then 2^m is applied by adding m's exponent bits directly
 *      to the IEEE 754 representation of q.
 */


